export type UiKey = keyof typeof ui.en;

export function t(locale: Locale, key: UiKey): string {
  return ui[locale][key] ?? ui.en[key];
}

/** Category/place heading: "Warungs in Ubud" / "Warung di Ubud". */
export function inWhere(locale: Locale, subject: string, where: string): string {
  return `${subject} ${t(locale, "inWhere")} ${where}`;
}

export function weekdayLabel(locale: Locale, day: string): string {
  const map: Record<string, UiKey> = {
    Mon: "dayMon",
    Tue: "dayTue",
    Wed: "dayWed",
    Thu: "dayThu",
    Fri: "dayFri",
    Sat: "daySat",
    Sun: "daySun",
  };
  const key = map[day];
  return key ? t(locale, key) : day;
}

export function placeTypeLabel(locale: Locale, type: string): string {
  if (type === "kabupaten") return t(locale, "placeTypeKabupaten");
  if (type === "kota") return t(locale, "placeTypeKota");
  if (type === "tourist_area") return t(locale, "placeTypeArea");
  return type;
}
